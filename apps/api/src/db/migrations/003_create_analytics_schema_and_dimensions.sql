  is_weekend BOOLEAN NOT NULL DEFAULT FALSE,
  is_holiday_pe BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

